/*
 * Память о недоступном Directus.
 *
 * Когда CMS не отвечает, каждый запрос к ней висит до таймаута соединения —
 * а запросов на сайте по одному на страницу. Переход на страницу тура ждал
 * две с половиной секунды впустую, хотя ответ всё равно приходил из моков.
 *
 * Поэтому первую же неудачу запоминаем на полминуты: всё это время страницы
 * отдаются из моков мгновенно, а потом сайт снова пробует достучаться —
 * поднявшуюся CMS не придётся ждать до перезагрузки вкладки.
 */
const COOLDOWN = 30_000

let downUntil = 0

/** Стоит ли вообще ходить в Directus прямо сейчас */
export function directusDown(): boolean {
  return Date.now() < downUntil
}

export function markDirectusDown(): void {
  downUntil = Date.now() + COOLDOWN
}
